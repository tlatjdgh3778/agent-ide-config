export const LUCIDE_NAMES: readonly string[] = NAMES.split(" ");

const simplify = (text: string) => text.toLowerCase().replace(/[\s_-]+/g, "");

/** Lucide names that contain the query, ignoring case, spaces and dashes; prefix matches first. */
export function searchIcons(query: string, limit: number, names = LUCIDE_NAMES): string[] {
  const needle = simplify(query);
  if (!needle) return [];
  const starts: string[] = [];
  const contains: string[] = [];
  for (const name of names) {
    const index = simplify(name).indexOf(needle);
    if (index === 0) starts.push(name);
    else if (index > 0) contains.push(name);
  }
  return [...starts, ...contains].slice(0, limit);
}
